// prisma/schema.prisma → prisma/init.sql (SQLite DDL)
// Prisma 엔진 바이너리 다운로드 없이 DB를 초기화하기 위한 보조 스크립트.
// 스키마를 바꾼 뒤 `node scripts/gen-sqlite-ddl.cjs` 를 실행해 init.sql 을 다시 생성한다.
const fs = require("fs");
const path = require("path");
const { getDMMF } = require("@prisma/internals");

const schemaPath = path.join(__dirname, "..", "prisma", "schema.prisma");
const datamodel = fs.readFileSync(schemaPath, "utf8");

const TYPE = { String: "TEXT", Int: "INTEGER", Float: "REAL", Boolean: "BOOLEAN", DateTime: "DATETIME", BigInt: "BIGINT", Bytes: "BLOB", Json: "JSONB", Decimal: "DECIMAL" };

function parseIndexes(model) {
  // @@index([a, b]) 파싱 (DMMF 에 일반 인덱스가 없음)
  const re = new RegExp(`model\\s+${model}\\s*\\{([\\s\\S]*?)\\n\\}`, "m");
  const body = (datamodel.match(re) || [])[1] || "";
  const out = [];
  for (const m of body.matchAll(/@@index\(\[([^\]]+)\]/g)) out.push(m[1].split(",").map((s) => s.trim()));
  return out;
}

function q(v) {
  return `'${String(v).replace(/'/g, "''")}'`;
}

getDMMF({ datamodel }).then((dmmf) => {
  const lines = ["-- generated by scripts/gen-sqlite-ddl.cjs — do not edit by hand", "PRAGMA foreign_keys = ON;"];
  for (const model of dmmf.datamodel.models) {
    const table = model.dbName || model.name;
    const cols = [];
    const constraints = [];
    for (const f of model.fields) {
      if (f.kind !== "scalar" && f.kind !== "enum") continue;
      let col = `"${f.name}" ${TYPE[f.type] || "TEXT"}`;
      if (f.isRequired) col += " NOT NULL";
      if (f.isId && !model.primaryKey) col += " PRIMARY KEY";
      if (f.hasDefaultValue && f.default !== undefined && typeof f.default !== "object") {
        col += ` DEFAULT ${typeof f.default === "string" ? q(f.default) : f.default}`;
      } else if (f.hasDefaultValue && f.default && typeof f.default === "object" && f.default.name === "now") {
        col += " DEFAULT CURRENT_TIMESTAMP";
      }
      cols.push(col);
    }
    if (model.primaryKey) constraints.push(`PRIMARY KEY (${model.primaryKey.fields.map((x) => `"${x}"`).join(", ")})`);
    for (const f of model.fields) {
      if (f.kind !== "object" || !f.relationFromFields || f.relationFromFields.length === 0) continue;
      const onDelete = f.relationOnDelete === "Cascade" ? "CASCADE" : f.relationOnDelete === "SetNull" ? "SET NULL" : f.isRequired ? "RESTRICT" : "SET NULL";
      constraints.push(
        `CONSTRAINT "${table}_${f.relationFromFields.join("_")}_fkey" FOREIGN KEY (${f.relationFromFields.map((x) => `"${x}"`).join(", ")}) REFERENCES "${f.type}" (${f.relationToFields.map((x) => `"${x}"`).join(", ")}) ON DELETE ${onDelete} ON UPDATE CASCADE`,
      );
    }
    lines.push(`CREATE TABLE IF NOT EXISTS "${table}" (\n  ${[...cols, ...constraints].join(",\n  ")}\n);`);
    for (const f of model.fields) {
      if (f.kind === "scalar" && f.isUnique) lines.push(`CREATE UNIQUE INDEX IF NOT EXISTS "${table}_${f.name}_key" ON "${table}"("${f.name}");`);
    }
    for (const u of model.uniqueIndexes || []) {
      lines.push(`CREATE UNIQUE INDEX IF NOT EXISTS "${table}_${u.fields.join("_")}_key" ON "${table}"(${u.fields.map((x) => `"${x}"`).join(", ")});`);
    }
    for (const idx of parseIndexes(model.name)) {
      lines.push(`CREATE INDEX IF NOT EXISTS "${table}_${idx.join("_")}_idx" ON "${table}"(${idx.map((x) => `"${x}"`).join(", ")});`);
    }
  }
  const out = path.join(__dirname, "..", "prisma", "init.sql");
  fs.writeFileSync(out, lines.join("\n") + "\n");
  console.log("wrote", out, `(${dmmf.datamodel.models.length} tables)`);
});
